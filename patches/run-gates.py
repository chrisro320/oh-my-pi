#!/usr/bin/env python3
"""Run the apply.sh gate menu in parallel, each gate in its own offline sandbox.

    python3 patches/run-gates.py --node-modules <runtime>/node_modules [selection] [options]

The gate list is never kept here: it is `apply.sh --print-gates` for the
runtime's version (exact registered match), and the per-gate metadata
(capabilities, flags) is `apply.sh --print-gate-map`, which is generated by the
same `_omp_gate` registrations. A real `apply.sh` calls this runner for its
regression suite, so installs and upgrade work use the identical code path.

Every gate runs in its own `bwrap --unshare-net --unshare-pid` with a private
HOME/XDG/TMPDIR (and its own /tmp), a read-only host filesystem, the live
`~/.omp` and `~/.bun/install` hidden, and the runtime tree bound read-only at a
neutral path. A gate registered with the `tree` flag (it writes into the
runtime) gets a private copy of the runtime instead (`cp -a`, ~1 s). The source
runtime is hashed before and after the whole batch and must not change.

Selection (default: every gate in the menu — the final acceptance run):
    --families F,...      families of plan.tsv (`apply.sh --print-families`) -> their capabilities
    --capabilities C,...  e.g. 0090,0092
    --gates G,...         explicit gate names (`verify-x.ts` or `verify-x`)
    --with-unscoped       also the gates registered with no capability (they are
                          not tied to any family; a subset run skips them by default)
    --list                print the selection and why, run nothing
Families/capabilities/gates are unioned. A capability selects every gate that
verifies it: the gates registered with it as their guard plus the ones that list
it in their COVERS argument (`apply.sh --print-gate-map`, 4th column). An empty
selector list (`--gates ""`) is an error, never the full menu. A capability
requested by name that no gate verifies (declared `_omp_no_gate`) exits 2.
Fix rounds run a subset; the full set runs once at the end.

`--validate-only` checks everything a run needs (bwrap, bun, runtime symlink
policy, writable output directory, menu and its capability coverage) and
runs nothing; `apply.sh` calls it before the first patch lands.

Exit status: 0 only when every selected gate passed, the runtime digest is
unchanged and the run was not interrupted; 1 when any gate failed, timed out or
did not run, the digest moved, or SIGINT/SIGTERM was received; 2 for a usage
or environment error.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import shutil
import signal
import subprocess
import sys
import tempfile
import threading
import time
from concurrent.futures import Future, ThreadPoolExecutor
from datetime import datetime, timezone
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from version_registry import require_registered  # noqa: E402

PACKAGES = {  # env root -> package directory under node_modules/@oh-my-pi
    "AGENT": "pi-coding-agent", "CORE": "pi-agent-core", "AI": "pi-ai",
    "SNAPCOMPACT": "snapcompact", "CATALOG": "pi-catalog", "TUI": "pi-tui",
}
FLAGS = {"tree", "companions", "exclusive", "slow"}
HIDDEN_UNDER_ACCOUNT_HOME = (".omp", ".bun/install", ".ssh", ".gnupg", ".aws")


def die(message: str, code: int = 2):
    print(f"run-gates: {message}", file=sys.stderr)
    raise SystemExit(code)


def now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="milliseconds")


def account_home() -> Path:
    import pwd
    return Path(pwd.getpwuid(os.getuid()).pw_dir)


# ---------------------------------------------------------------- environment

def tool_dirs() -> list[str]:
    dirs: list[str] = []
    for tool in ("bun", "tsc", "node"):
        found = shutil.which(tool)
        if found and str(Path(found).parent) not in dirs:
            dirs.append(str(Path(found).parent))
    return dirs + ["/usr/local/bin", "/usr/bin", "/bin"]


def sandbox_probe() -> str | None:
    """None when a gate sandbox can be built here, else the reason."""
    if not shutil.which("bwrap"):
        return "bwrap is not installed (gates must run offline in bwrap --unshare-net)"
    if not shutil.which("bun"):
        return "bun is not on PATH"
    probe = subprocess.run(
        ["bwrap", "--die-with-parent", "--unshare-net", "--unshare-pid", "--ro-bind", "/", "/",
         "--dev", "/dev", "--proc", "/proc", "true"],
        capture_output=True, text=True)
    if probe.returncode != 0:
        return f"bwrap cannot build the gate sandbox: {probe.stderr.strip() or probe.returncode}"
    return None


def apply_query(mode: str, version: str) -> list[str]:
    env = {"PATH": os.environ.get("PATH", "/usr/bin:/bin"), "HOME": tempfile.gettempdir(),
           "OMP_PATCH_VERSION": version}
    result = subprocess.run(["bash", str(HERE / "apply.sh"), mode], env=env, capture_output=True, text=True)
    if result.returncode != 0:
        die(f"apply.sh {mode} failed ({result.returncode}): {result.stderr.strip()}")
    return result.stdout.splitlines()


# ------------------------------------------------------------- runtime digest

def scan_runtime(node_modules: Path) -> list[tuple[str, Path | str]]:
    """Every file and symlink of the runtime, relative to the node_modules parent.

    Absolute or escaping symlinks are refused: the tree is re-rooted into each gate sandbox.
    """
    base = node_modules.parent
    entries: list[tuple[str, Path | str]] = []
    for directory, dirnames, filenames in os.walk(node_modules):
        for name in dirnames + filenames:
            path = Path(directory) / name
            if path.is_symlink():
                target = os.readlink(path)
                resolved = os.path.normpath(os.path.join(directory, target))
                if os.path.isabs(target) or not (resolved + os.sep).startswith(str(node_modules) + os.sep):
                    die(f"runtime symlink cannot be re-rooted into a gate sandbox: {path} -> {target}")
                entries.append((str(path.relative_to(base)), f"symlink:{target}"))
            elif path.is_file():
                entries.append((str(path.relative_to(base)), path))
    return entries


def runtime_digest(node_modules: Path, jobs: int) -> tuple[str, int]:
    """sha256 over sorted 'relative-path\\0file-sha256\\n' (symlinks: 'symlink:<target>').

    Paths are relative to the directory holding node_modules.
    """
    entries = scan_runtime(node_modules)

    def one(entry: tuple[str, Path | str]) -> bytes:
        rel, what = entry
        if isinstance(what, str):
            digest = what
        else:
            hasher = hashlib.sha256()
            with open(what, "rb") as handle:
                for chunk in iter(lambda: handle.read(1 << 20), b""):
                    hasher.update(chunk)
            digest = hasher.hexdigest()
        return f"{rel}\0{digest}\n".encode()

    entries.sort(key=lambda entry: entry[0])
    with ThreadPoolExecutor(max_workers=jobs) as pool:
        total = hashlib.sha256()
        for line in pool.map(one, entries, chunksize=64):
            total.update(line)
    return total.hexdigest(), len(entries)


# ------------------------------------------------------------------ selection

class Menu:
    def __init__(self, version: str):
        self.gates = apply_query("--print-gates", version)
        rows = [line.split("\t") for line in apply_query("--print-gate-map", version)]
        if [row[0] for row in rows] != self.gates or len(set(self.gates)) != len(self.gates):
            die("apply.sh --print-gate-map disagrees with --print-gates (or lists a gate twice)")
        self.caps: dict[str, list[str]] = {}
        self.covers: dict[str, list[str]] = {}
        self.flags: dict[str, set[str]] = {}
        for row in rows:
            if len(row) != 4:
                die(f"malformed gate-map row: {row!r}")
            gate, caps, flags, covers = row
            self.caps[gate] = [cap for cap in caps.split(",") if cap]
            self.covers[gate] = [cap for cap in covers.split(",") if cap]
            self.flags[gate] = {flag for flag in flags.split(",") if flag}
            unknown = self.flags[gate] - FLAGS
            if unknown or Path(gate).name != gate or not (HERE / gate).is_file():
                die(f"invalid gate registration: {gate} flags={sorted(self.flags[gate])}")
        self.capabilities = set(apply_query("--print-capabilities", version))
        # capability -> gates verifying it (guard or covers); full-menu selection never uses this
        self.verifiers: dict[str, list[str]] = {}
        for gate in self.gates:
            for cap in self.caps[gate] + self.covers[gate]:
                self.verifiers.setdefault(cap, []).append(gate)
        self.no_gate = dict(line.split("\t", 1) for line in apply_query("--print-no-gate", version))
        for cap in sorted(self.capabilities):  # apply.sh already refuses this; re-checked here, fail closed
            if cap not in self.verifiers and cap not in self.no_gate:
                die(f"capability {cap} has neither a gate nor an _omp_no_gate declaration")
        self.families: dict[str, list[str]] = {}
        for line in apply_query("--print-families", version):
            family, caps = line.split("\t")
            self.families[family] = caps.split(",")


def select(menu: Menu, args) -> dict[str, list[str]]:
    """Ordered {gate: [reasons]} for the requested subset (or everything)."""
    if not (args.families or args.capabilities or args.gates or args.with_unscoped):
        return {gate: ["full menu"] for gate in menu.gates}
    chosen: dict[str, list[str]] = {}
    wanted_caps: dict[str, list[str]] = {}
    for family in args.families:
        if family not in menu.families:
            die(f"unknown family {family!r}; plan.tsv families: {', '.join(menu.families)}")
        for cap in menu.families[family]:
            wanted_caps.setdefault(cap, []).append(f"family {family}")
    for cap in args.capabilities:
        if cap not in menu.capabilities:
            die(f"capability {cap!r} is not in this plan; known: {' '.join(sorted(menu.capabilities))}")
        if cap not in menu.verifiers:
            die(f"capability {cap} has no gate: {menu.no_gate[cap]}")
        wanted_caps.setdefault(cap, []).append(f"capability {cap}")
    for cap in wanted_caps:
        if cap not in menu.verifiers:
            print(f"note: capability {cap} (family selection) has no gate: {menu.no_gate[cap]}", file=sys.stderr)
    for gate in menu.gates:
        reasons = [f"{why} ({'guard' if cap in menu.caps[gate] else 'covers'} of {gate})"
                   for cap in menu.caps[gate] + menu.covers[gate] for why in wanted_caps.get(cap, [])]
        if reasons:
            chosen[gate] = list(dict.fromkeys(reasons))
    for name in args.gates:
        match = [gate for gate in menu.gates if gate in (name, f"{name}.ts", f"{name}.sh")]
        if not match:
            die(f"gate {name!r} is not in this plan's menu (apply.sh --print-gates)")
        chosen.setdefault(match[0], []).append("--gates")
    if args.with_unscoped:
        for gate in menu.gates:
            if not menu.caps[gate]:
                chosen.setdefault(gate, []).append("--with-unscoped")
    ordered = {gate: chosen[gate] for gate in menu.gates if gate in chosen}
    if not ordered:
        die("the selection matches no gate; nothing would run, which is a failure")
    return ordered


# -------------------------------------------------------------------- running

class Runner:
    def __init__(self, args, node_modules: Path, version: str, out: Path, menu: Menu, companions: Path | None):
        self.args, self.node_modules, self.version = args, node_modules, version
        self.out, self.menu, self.companions = out, menu, companions
        self.stop = threading.Event()
        self.lock = threading.Lock()
        self.children: set[subprocess.Popen] = set()
        self.account = account_home()
        self.path = ":".join(tool_dirs())

    # one gate -------------------------------------------------------------
    def environment(self, base: Path, runtime_nm: Path, gate: str) -> dict[str, str]:
        nm = runtime_nm / "@oh-my-pi"
        env = {
            "PATH": self.path, "HOME": str(base / "home"),
            "XDG_CONFIG_HOME": str(base / "config"), "XDG_CACHE_HOME": str(base / "cache"),
            "XDG_DATA_HOME": str(base / "data"), "XDG_STATE_HOME": str(base / "state"),
            "XDG_RUNTIME_DIR": str(base / "run"), "TMPDIR": "/tmp",
            "PI_CODING_AGENT_DIR": str(base / "agent"), "TERM": "dumb", "LANG": "C.UTF-8", "NO_COLOR": "1",
            "OMP_PATCH_VERSION": self.version, "OMP_PATCH_PLAN": "deployed", "OMP_PATCH_OFFLINE_VERIFY": "1",
            "OMP_PATCH_VERIFY_NM": str(nm), "OMP_PAYLOAD_ARCHIVE": str(base / "payloads"),
            "OMP_RESUME_EVENT_LOG": str(base / "resume-events.jsonl"),
        }
        env.update({f"OMP_PATCH_VERIFY_{key}_ROOT": str(nm / package) for key, package in PACKAGES.items()})
        if "companions" in self.menu.flags[gate]:
            env["OMP_EXTENSIONS_STAGED_DIR"] = str(self.companions)
        return env

    def command(self, base: Path, runtime_nm: Path, gate: str, env: dict[str, str]) -> list[str]:
        cmd = ["bwrap", "--die-with-parent", "--new-session", "--unshare-net", "--unshare-pid",
               "--unshare-ipc", "--unshare-uts", "--ro-bind", "/", "/", "--dev", "/dev", "--proc", "/proc",
               "--bind", str(base / "tmp"), "/tmp"]
        for rel in HIDDEN_UNDER_ACCOUNT_HOME:
            hidden = self.account / rel
            if hidden.is_dir():
                cmd += ["--tmpfs", str(hidden)]
        # Re-bind after the hiding/tmp mounts: the ledger may live under ~/.omp or /tmp.
        cmd += ["--ro-bind", str(HERE), str(HERE)]
        if "companions" in self.menu.flags[gate]:
            cmd += ["--ro-bind", str(self.companions), str(self.companions)]
        cmd += ["--bind", str(base), str(base)]
        if "tree" not in self.menu.flags[gate]:
            cmd += ["--ro-bind", str(self.node_modules), str(runtime_nm)]
        runner = "bash" if gate.endswith(".sh") else shutil.which("bun")
        return cmd + ["--chdir", env["HOME"], "--", runner, str(HERE / gate)]

    def prepare(self, base: Path, gate: str) -> Path:
        for leaf in ("home", "config", "cache", "data", "state", "run", "agent", "tmp", "payloads"):
            (base / leaf).mkdir(parents=True, exist_ok=True)
        runtime_nm = base / "runtime" / "node_modules"
        runtime_nm.parent.mkdir(parents=True, exist_ok=True)
        if "tree" in self.menu.flags[gate]:
            subprocess.run(["cp", "-a", "--reflink=auto", str(self.node_modules), str(runtime_nm)], check=True)
        else:
            runtime_nm.mkdir(parents=True, exist_ok=True)  # mount point for the read-only bind
        global_root = base / "home" / ".bun" / "install" / "global"
        global_root.mkdir(parents=True, exist_ok=True)
        (global_root / "node_modules").symlink_to(runtime_nm, target_is_directory=True)
        (base / "home" / ".bun" / "bin").mkdir(parents=True, exist_ok=True)
        (base / "home" / ".bun" / "bin" / "omp").symlink_to(
            "../install/global/node_modules/@oh-my-pi/pi-coding-agent/src/cli.ts")
        return runtime_nm

    def run_gate(self, gate: str, reasons: list[str]) -> dict:
        stem = Path(gate).stem
        log = self.out / "logs" / f"{stem}.log"
        row = {"gate": gate, "status": "NOT_RUN", "exit": None, "seconds": 0.0, "log": str(log),
               "flags": sorted(self.menu.flags[gate]), "capabilities": self.menu.caps[gate],
               "selected_by": reasons, "gate_sha256": hashlib.sha256((HERE / gate).read_bytes()).hexdigest()}
        if self.stop.is_set():
            row["detail"] = "runner interrupted before this gate started"
            return row
        if "companions" in self.menu.flags[gate] and self.companions is None:
            row["detail"] = "needs --companions (the staged companion fixture)"
            self.report(row)
            return row
        base = self.out / "work" / stem
        started = time.monotonic()
        row["started"] = now()
        try:
            runtime_nm = self.prepare(base, gate)
            env = self.environment(base, runtime_nm, gate)
            cmd = self.command(base, runtime_nm, gate, env)
            with open(log, "wb") as handle:
                handle.write(f"# {gate} {now()}\n# {' '.join(cmd)}\n".encode())
                handle.flush()
                # Recheck cancellation under the lock that registers children: a stop requested while
                # this gate was being prepared (tree copy) must not be followed by a launch.
                with self.lock:
                    child = None
                    if not self.stop.is_set():
                        child = subprocess.Popen(cmd, env=env, cwd=base, stdin=subprocess.DEVNULL, stdout=handle,
                                                 stderr=subprocess.STDOUT, start_new_session=True)
                        self.children.add(child)
                if child is None:
                    row["detail"] = "runner interrupted while this gate was being prepared"
                    handle.write(b"\n# not started: runner interrupted\n")
                else:
                    try:
                        code = child.wait(timeout=self.args.timeout)
                        row["status"] = "PASS" if code == 0 else "FAIL"
                    except subprocess.TimeoutExpired:
                        self.kill(child)
                        code = 124
                        row["status"] = "TIMEOUT"
                        row["detail"] = f"no exit within {self.args.timeout}s; process group killed"
                        handle.write(f"\n# TIMEOUT after {self.args.timeout}s\n".encode())
                    except KeyboardInterrupt:
                        self.interrupt()
                        raise
                    finally:
                        with self.lock:
                            self.children.discard(child)
                    if self.stop.is_set() and row["status"] == "FAIL":
                        row["status"] = "NOT_RUN"
                        row["detail"] = "runner interrupted while this gate was running"
                    row["exit"] = code
                    handle.write(f"\n# exit {code} {now()}\n".encode())
        except (OSError, subprocess.CalledProcessError) as error:
            row["status"], row["detail"] = "NOT_RUN", f"could not start: {error}"
        row["seconds"] = round(time.monotonic() - started, 2)
        row["finished"] = now()
        if row["status"] == "PASS" and not self.args.keep_work:
            shutil.rmtree(base, ignore_errors=True)
        else:
            row["work_dir"] = str(base)
        self.report(row)
        return row

    def kill(self, child: subprocess.Popen) -> None:
        try:
            os.killpg(child.pid, signal.SIGKILL)
        except ProcessLookupError:
            pass
        child.wait()

    def report(self, row: dict) -> None:
        with self.lock:
            print(f"{row['status']:<8} {row['seconds']:>7.1f}s  {row['gate']:<62} {row['log'] if row['status'] != 'PASS' else ''}",
                  flush=True)

    def interrupt(self) -> None:
        self.stop.set()
        with self.lock:
            for child in list(self.children):
                try:
                    os.killpg(child.pid, signal.SIGKILL)
                except ProcessLookupError:
                    pass

    # the batch ------------------------------------------------------------
    def run(self, selection: dict[str, list[str]]) -> list[dict]:
        gates = list(selection)
        exclusive = [g for g in gates if "exclusive" in self.menu.flags[g]]
        parallel = [g for g in gates if g not in exclusive]
        parallel.sort(key=lambda g: "slow" not in self.menu.flags[g])  # stable: slow first, menu order otherwise
        rows: dict[str, dict] = {}
        futures: dict[str, Future] = {}
        pool = ThreadPoolExecutor(max_workers=self.args.jobs)
        try:
            futures = {g: pool.submit(self.run_gate, g, selection[g]) for g in parallel}
            for gate, future in futures.items():
                rows[gate] = future.result()
            for gate in exclusive:  # alone: nothing else is running
                rows[gate] = self.run_gate(gate, selection[gate])
        except KeyboardInterrupt:
            self.interrupt()
        finally:
            # Queued gates are cancelled and running children already killed (interrupt) BEFORE the
            # shutdown wait, so a hung gate cannot hold an interrupted batch for its whole timeout.
            for future in futures.values():
                future.cancel()
            pool.shutdown(wait=True, cancel_futures=True)
        for gate, future in futures.items():
            if gate not in rows and future.done() and not future.cancelled() and future.exception() is None:
                rows[gate] = future.result()
        return [rows[g] if g in rows else
                {"gate": g, "status": "NOT_RUN", "exit": None, "seconds": 0.0, "log": str(self.out / "logs" / f"{Path(g).stem}.log"),
                 "detail": "runner interrupted before this gate started", "selected_by": selection[g]}
                for g in gates]


def csv(value: str) -> list[str]:
    return [part.strip() for part in value.split(",") if part.strip()]


def reserve_out(requested: Path | None) -> Path:
    """The evidence directory, created and proven writable (it must not live under /tmp)."""
    base = Path(os.environ.get("OMP_GATES_WORK_DIR") or "/var/tmp")
    try:
        out = (requested or Path(tempfile.mkdtemp(prefix="omp-gates-", dir=base))).resolve()
        if out == Path("/tmp") or Path("/tmp") in out.parents:
            die("--out must not be under /tmp: every gate sandbox replaces /tmp with a private directory")
        for leaf in ("logs", "work"):
            (out / leaf).mkdir(parents=True, exist_ok=True)
            probe = out / leaf / ".writable"
            probe.write_text("")
            probe.unlink()
    except OSError as error:
        die(f"cannot use the gate output directory ({requested or base}): {error}; "
            f"set OMP_GATES_WORK_DIR or --out to a writable directory outside /tmp")
    return out


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--node-modules", type=Path, help="runtime node_modules directory holding @oh-my-pi (read-only source)")
    parser.add_argument("--version", help="plan version; default: the runtime's pi-coding-agent version (must be registered)")
    parser.add_argument("--companions", type=Path, help="staged companion fixture for gates flagged `companions`")
    parser.add_argument("--families", type=csv, default=None, metavar="F,..")
    parser.add_argument("--capabilities", type=csv, default=None, metavar="C,..")
    parser.add_argument("--gates", type=csv, default=None, metavar="G,..")
    parser.add_argument("--with-unscoped", action="store_true")
    parser.add_argument("--list", action="store_true", help="print the selection and exit")
    parser.add_argument("-j", "--jobs", type=int, default=max(2, (os.cpu_count() or 4) // 2), help="parallel gates (default: CPUs/2; 1 = serial)")
    parser.add_argument("--timeout", type=int, default=900, help="seconds per gate (default 900)")
    parser.add_argument("--out", type=Path, help="evidence directory (logs/, work/); default a fresh dir under /var/tmp")
    parser.add_argument("--json", type=Path, help="write the JSON receipt here")
    parser.add_argument("--keep-work", action="store_true", help="keep every gate's private dirs (default: only failures)")
    parser.add_argument("--validate-only", action="store_true",
                        help="check bwrap/bun, runtime symlinks, output dir, menu and coverage; run nothing")
    args = parser.parse_args()
    for name in ("families", "capabilities", "gates"):
        value = getattr(args, name)
        if value is None:
            setattr(args, name, [])
        elif not value:
            die(f"--{name} was given an empty list; an empty selector never means the full menu "
                f"(omit every selector to run the full menu)")

    if args.jobs < 1 or args.timeout < 1:
        die("--jobs and --timeout must be positive")
    if not args.node_modules:
        die("--node-modules is required")
    node_modules = args.node_modules.resolve(strict=True)
    agent_manifest = node_modules / "@oh-my-pi" / PACKAGES["AGENT"] / "package.json"
    if not agent_manifest.is_file():
        die(f"{node_modules} has no @oh-my-pi/{PACKAGES['AGENT']}")
    for package in PACKAGES.values():
        if not (node_modules / "@oh-my-pi" / package).is_dir():
            die(f"{node_modules}/@oh-my-pi/{package} is missing")
    tree_version = json.loads(agent_manifest.read_text()).get("version")
    version = args.version or tree_version
    if version != tree_version:
        die(f"--version {version} but the runtime is {tree_version}")
    require_registered(version, "run-gates: runtime version")

    if not args.list:
        problem = sandbox_probe()
        if problem:
            die(problem)
    menu = Menu(version)  # also refuses a plan capability with neither a gate nor a _omp_no_gate declaration
    selection = select(menu, args)
    if args.list:
        for gate, reasons in selection.items():
            print(f"{gate}\t{','.join(menu.caps[gate]) or '-'}\t{','.join(menu.covers[gate]) or '-'}\t"
                  f"{','.join(sorted(menu.flags[gate])) or '-'}\t{'; '.join(reasons)}")
        skipped = [g for g in menu.gates if g not in selection]
        print("# columns: gate, guard capabilities, covered capabilities, flags, why selected", file=sys.stderr)
        print(f"# {len(selection)} of {len(menu.gates)} gates selected; {len(skipped)} not selected", file=sys.stderr)
        return 0

    companions = None
    needs_companions = any("companions" in menu.flags[g] for g in selection)
    if needs_companions and args.companions:
        companions = args.companions.resolve(strict=True)
        if not companions.is_dir():
            die(f"--companions {companions} is not a directory")
    if args.validate_only:
        if needs_companions and companions is None:
            die("the selected gates need --companions (the staged companion fixture)")
        entries = len(scan_runtime(node_modules))  # symlink policy: absolute/escaping links are refused
        reserved = reserve_out(args.out)
        if not args.out:
            shutil.rmtree(reserved, ignore_errors=True)
        print(f"validate-only: ok ({len(selection)} gates, {entries} runtime entries, output {reserved})")
        return 0
    out = reserve_out(args.out)

    hash_jobs = min(16, os.cpu_count() or 4)
    started_at = time.monotonic()
    digest_before, files = runtime_digest(node_modules, hash_jobs)
    print(f"runtime {node_modules} version {version}: {files} entries, sha256 {digest_before[:16]}…")
    args.jobs = min(args.jobs, len(selection))
    print(f"selected {len(selection)} of {len(menu.gates)} gates, {args.jobs} parallel, "
          f"timeout {args.timeout}s each; logs in {out}/logs", flush=True)
    if (args.families or args.capabilities) and not args.with_unscoped:
        unscoped = sum(1 for g in menu.gates if not menu.caps[g])
        print(f"subset run: {unscoped} gates tied to no capability are not selected (--with-unscoped adds them); "
              f"the final acceptance runs the full menu once")

    runner = Runner(args, node_modules, version, out, menu, companions)
    signal.signal(signal.SIGTERM, lambda *_: runner.interrupt())
    batch_started = time.monotonic()
    rows = runner.run(selection)
    wall = time.monotonic() - batch_started
    digest_after, _ = runtime_digest(node_modules, hash_jobs)
    unchanged = digest_after == digest_before

    tally: dict[str, int] = {}
    for row in rows:
        tally[row["status"]] = tally.get(row["status"], 0) + 1
    bad = [row for row in rows if row["status"] != "PASS"]
    serial_sum = round(sum(row["seconds"] for row in rows), 1)
    interrupted = runner.stop.is_set()
    status = "PASS" if not bad and unchanged and not interrupted else "FAIL"
    print(f"\n{len(rows)} gates: " + ", ".join(f"{count} {name}" for name, count in sorted(tally.items()))
          + f"; wall {wall:.1f}s (sum of gate times {serial_sum}s, {args.jobs} jobs); runtime digest "
          + ("unchanged" if unchanged else f"CHANGED {digest_before[:16]}… -> {digest_after[:16]}…"))
    if bad:
        print("FAILED: " + ", ".join(f"{row['gate']} [{row['status']}]" for row in bad), file=sys.stderr)
    if not unchanged:
        print("FAILED: the source runtime tree changed while the gates ran", file=sys.stderr)
    if interrupted:
        print("FAILED: interrupted by SIGINT/SIGTERM; gates that had not finished are NOT_RUN", file=sys.stderr)
    receipt = {
        "status": status, "interrupted": interrupted, "version": version, "node_modules": str(node_modules), "finished": now(),
        "runner_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        "apply_sh_sha256": hashlib.sha256((HERE / "apply.sh").read_bytes()).hexdigest(),
        "jobs": args.jobs, "timeout_s": args.timeout, "wall_s": round(wall, 1), "total_s": round(time.monotonic() - started_at, 1),
        "gate_seconds_sum": serial_sum, "out": str(out),
        "selection": {"menu_total": len(menu.gates), "selected": len(selection), "families": args.families,
                      "capabilities": args.capabilities, "gates": args.gates, "with_unscoped": args.with_unscoped},
        "runtime_digest": {"method": "sha256 over sorted 'relative-path\\0file-sha256\\n' (paths relative to the node_modules parent)",
                           "entries": files, "before": digest_before, "after": digest_after, "unchanged": unchanged},
        "tally": tally, "failing": [row["gate"] for row in bad], "gates": rows,
    }
    if args.json:
        args.json.parent.mkdir(parents=True, exist_ok=True)
        args.json.write_text(json.dumps(receipt, indent=2, ensure_ascii=True) + "\n")
    return 0 if status == "PASS" else 1


